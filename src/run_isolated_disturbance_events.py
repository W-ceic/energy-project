"""Isolated single-disturbance-event DMC DV-information experiment.

This script deliberately compares only ``DMC-without-DV`` and ``DMC-DV hold``.
It reuses the actual scenario-7 event definitions generated by the existing
benchmark, shifts their onset to 180 min, and never supplies future true DV
values to the controller.  The source benchmark itself is not modified.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, Iterable, List, Tuple

import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
import numpy as np
import pandas as pd

import run_robust_hrsg_simulation as base


ROOT = Path(__file__).resolve().parents[1]
SOURCE_OUT = ROOT / "outputs" / "offline_simulation"
OUT = ROOT / "outputs" / "isolated_disturbance_events"
OUT.mkdir(parents=True, exist_ok=True)

WITHOUT = "DMC-without-DV"
HOLD = "DMC-DV hold"
CASES = {
    "A_condensate_flow_only": {"label": "Condensate-flow-only", "kind": "condensate"},
    "B_makeup_flow_only": {"label": "Makeup-flow-only", "kind": "makeup"},
    "C_unmeasured_only": {"label": "Unmeasured-disturbance-only", "kind": "unmeasured"},
}
T = 360
T0 = 180
WINDOW_START, WINDOW_END = T0 - 20, T0 + 100
EARLY_END = T0 + 5
RECOVERY_BAND = 0.005
RECOVERY_HOLD_MIN = 10
TEST_IDS = tuple(range(1, 31))


def _stage_vector_from_seed(seed: int, T: int, mismatch: bool) -> np.ndarray:
    """Reproduce the saved generator's scenario-specific coloured-event vector.

    The original event JSON saves the vector norm but not its three components.
    Replaying the unchanged generator's random-number consumption recovers the
    exact vector, rather than inventing an approximation.
    """
    rng = np.random.default_rng(seed)
    if mismatch:
        rng.uniform(-0.15, 0.15, base.KM.shape)
        rng.uniform(-0.20, 0.20, base.TAUM.shape)
        rng.choice(np.array([-2, -1, 0, 1, 2]), base.THETAM.shape)
    for _j in range(base.ND):
        for _k in range(1, T):
            rng.normal(0, 0.004)
    rng.choice(np.arange(70, max(71, T - 45)), size=3, replace=False)
    for _ in range(3):
        rng.choice([-1, 1])
        rng.uniform(0.08, 0.25)  # bounds do not alter the random draw consumed
        rng.choice(["step", "ramp", "pulse"])
        rng.integers(25, 55)
    rng.normal(0, base.W_STD * 0.6)
    eta_std = base.W_STD * np.sqrt(1 - base.AR ** 2)
    for _k in range(1, T):
        rng.normal(0, eta_std)
    rng.integers(150, max(151, T - 60))
    rng.integers(20, 50)
    return rng.normal([0.006, 0.006, 0.010], [0.002, 0.002, 0.003])


def _source_events() -> Tuple[base.Scenario, Dict[str, Dict], np.ndarray]:
    """Load scenario 7 by its original seed and audit its saved event metadata."""
    events = json.loads((SOURCE_OUT / "scenario_events.json").read_text(encoding="utf-8"))
    stored = next(x for x in events if x["scenario_id"] == 7)
    scn = base.create_scenario(7, int(stored["random_seed"]), T, True, True, "source scenario 7")
    by_name: Dict[str, Dict] = {}
    for event in scn.events:
        if event["dv"] == "Cond_Flow" and event["kind"] == "ramp" and event["duration_min"] == 38:
            by_name["condensate"] = event
        elif event["dv"] == "Makeup_Flow" and event["kind"] == "pulse" and event["duration_min"] == 28:
            by_name["makeup"] = event
        elif event["dv"] == "unmeasured_colored_disturbance" and event["duration_min"] == 26:
            by_name["unmeasured"] = event
    if set(by_name) != {"condensate", "makeup", "unmeasured"}:
        raise RuntimeError("Could not recover all three requested scenario-7 event templates")
    stage = _stage_vector_from_seed(scn.seed, T, True)
    if not np.isclose(np.linalg.norm(stage), by_name["unmeasured"]["amplitude"], rtol=0, atol=1e-14):
        raise RuntimeError("Scenario-7 coloured-event vector failed exact norm audit")
    return scn, by_name, stage


def _shifted_dv_template(event: Dict) -> np.ndarray:
    shifted = dict(event)
    shifted["start_min"] = T0
    arr = np.zeros((T, base.ND))
    base.apply_event(arr, shifted)
    return arr


def _background_w(scn: base.Scenario) -> np.ndarray:
    """Remove only its deterministic coloured event, retaining the AR(1) path."""
    event = next(e for e in scn.events if e["dv"] == "unmeasured_colored_disturbance")
    stage = _stage_vector_from_seed(scn.seed, scn.T, scn.mismatch)
    result = scn.w.copy()
    result[event["start_min"] : event["start_min"] + event["duration_min"]] -= stage
    return result


def make_isolated_scenario(case: str, scenario_id: int, level: str, templates: Dict[str, Dict], source_stage: np.ndarray) -> base.Scenario:
    """Create a matched clean or stochastic single-event scenario."""
    clean = level == "clean"
    seed = base.MASTER_SEED + 7 if clean else base.MASTER_SEED + scenario_id
    original = base.create_scenario(
        7 if clean else scenario_id, seed, T, not clean, not clean,
        "clean deterministic demonstration" if clean else "matched stochastic isolated event",
    )
    # All measured-DV background trajectories are removed.  Only the selected
    # scenario-7 waveform is applied; measurement-noise draws remain untouched.
    dv = np.zeros((T, base.ND))
    w = np.zeros((T, base.NY)) if clean else _background_w(original)
    event_records: List[Dict] = []
    kind = CASES[case]["kind"]
    if kind in ("condensate", "makeup"):
        dv += _shifted_dv_template(templates[kind])
        rec = dict(templates[kind]); rec["start_min"] = T0; event_records.append(rec)
    else:
        event = templates["unmeasured"]
        w[T0 : T0 + event["duration_min"]] += source_stage
        rec = dict(event); rec["start_min"] = T0; event_records.append(rec)
    return base.Scenario(
        scenario_id, seed, T, original.Kp.copy(), original.thetap.copy(), original.taup.copy(),
        dv, original.dv_meas_noise.copy(), w, original.y_noise.copy(), event_records,
        original.mismatch, original.label,
    )


def run_controller(scn: base.Scenario, controller: str, pidpars: Dict[str, float], case: str, level: str) -> pd.DataFrame:
    plant = base.FOPDTPlant(scn.Kp, scn.thetap, scn.taup)
    dmc = base.DMCController("hold", base.PIDController(pidpars))
    reference_dv = np.zeros(base.ND)
    rows: List[Dict] = []
    for k in range(scn.T):
        ytrue = plant.output() + scn.w[k]
        ymeas = ytrue + scn.y_noise[k]
        dtrue = scn.dv_true[k]
        dmeas = dtrue + scn.dv_meas_noise[k]
        dctrl = reference_dv if controller == WITHOUT else dmeas
        u, status, _pred, active, dhat = dmc.step(ymeas, dctrl)
        row: Dict = {
            "level": level, "case": case, "scenario_id": scn.scenario_id, "random_seed": scn.seed,
            "time": k, "time_min": k, "controller": controller,
            "controller_DV_mode": "nominal_zero" if controller == WITHOUT else "measured_DV_hold",
            "DMC_active": int(active), "QP_success": int(dmc.last_qp_feasible),
            "QP_attempted": int(dmc.last_qp_attempted), "constraint_rate_active": int(status["rate"]),
            "constraint_amplitude_active": int(status["amp"]), "constraint_cv_active": int(status["cv"]),
        }
        for i, name in enumerate(base.CV_NAMES):
            row[f"{name}_true"] = ytrue[i]
            row[f"{name}_measured"] = ymeas[i]
            row[f"{name}_unmeasured_dist"] = scn.w[k, i]
        for j, name in enumerate(base.MV_NAMES):
            row[name] = u[j]
        for j, name in enumerate(base.DV_NAMES):
            row[f"{name}_true"] = dtrue[j]
            row[f"{name}_measured"] = dmeas[j]
            row[f"{name}_controller_input"] = dctrl[j]
            row[f"{name}_predicted_1step"] = dhat[0, j]
        rows.append(row)
        # This is the second required information boundary: no-DV advances its
        # internal model with nominal zero, while hold advances with d_meas.
        dmc.advance(u, dctrl)
        plant.update(u, dtrue)
    frame = pd.DataFrame(rows)
    for mv in base.MV_NAMES:
        frame[f"d{mv}"] = frame[mv].diff().fillna(frame[mv])
    return frame


def _recovery_time(e: np.ndarray, time: np.ndarray) -> float:
    post = np.where(time >= T0)[0]
    for pos in post:
        end = pos + RECOVERY_HOLD_MIN
        if end <= len(e) and np.all(np.abs(e[pos:end]) <= RECOVERY_BAND):
            return float(time[pos] - T0)
    return np.nan


def _onset(du: np.ndarray, time: np.ndarray) -> float:
    threshold = 0.10 * float(np.max(np.abs(base.DUMAX)))
    choices = np.where((time >= T0) & (np.abs(du) >= threshold))[0]
    return float(time[choices[0]] - T0) if len(choices) else np.nan


def event_metrics(frame: pd.DataFrame) -> Dict:
    time = frame.time_min.to_numpy()
    event_mask = (time >= WINDOW_START) & (time <= WINDOW_END)
    early_mask = (time >= T0) & (time <= EARLY_END)
    values: Dict = {
        "case": frame.case.iloc[0], "scenario_id": int(frame.scenario_id.iloc[0]),
        "controller": frame.controller.iloc[0], "level": frame.level.iloc[0],
    }
    for i, cv in enumerate(("HP_pH", "MP_pH")):
        error = frame[f"{cv}_true"].to_numpy() - base.YSP[i]
        display = "HP" if cv == "HP_pH" else "IP"
        values[f"{display}_full_IAE"] = float(np.sum(np.abs(error)) * base.TS)
        values[f"{display}_full_RMSE"] = float(np.sqrt(np.mean(error ** 2)))
        values[f"{display}_event_IAE"] = float(np.sum(np.abs(error[event_mask])) * base.TS)
        values[f"{display}_peak_deviation"] = float(np.max(np.abs(error[event_mask])))
        values[f"{display}_recovery_time"] = _recovery_time(error, time)
    values["Total_event_pH_IAE"] = values["HP_event_IAE"] + values["IP_event_IAE"]
    values["Total_full_pH_IAE"] = values["HP_full_IAE"] + values["IP_full_IAE"]
    for mv in base.MV_NAMES:
        short = "MV1" if mv == base.MV_NAMES[0] else "MV2"
        du = frame[f"d{mv}"].to_numpy()
        values[f"{short}_TV_event"] = float(np.sum(np.abs(du[event_mask])))
        values[f"Early_{short}_TV"] = float(np.sum(np.abs(du[early_mask])))
        values[f"max_abs_d{short.lower()}"] = float(np.max(np.abs(du[event_mask])))
        values[f"{short}_response_onset_min"] = _onset(du, time)
    values["Total_MV_TV_event"] = values["MV1_TV_event"] + values["MV2_TV_event"]
    values["Early_Total_MV_TV"] = values["Early_MV1_TV"] + values["Early_MV2_TV"]
    values["QP_failures"] = int(np.sum(frame.QP_success.to_numpy() == 0))
    values["DMC_active_ratio"] = float(frame.DMC_active.mean())
    return values


def paired_statistics(metrics: pd.DataFrame) -> pd.DataFrame:
    metric_columns = [
        "HP_full_IAE", "IP_full_IAE", "HP_full_RMSE", "IP_full_RMSE", "Total_full_pH_IAE",
        "HP_event_IAE", "IP_event_IAE", "Total_event_pH_IAE", "HP_peak_deviation", "IP_peak_deviation",
        "HP_recovery_time", "IP_recovery_time", "Total_MV_TV_event", "MV1_TV_event", "MV2_TV_event",
        "Early_Total_MV_TV", "Early_MV1_TV", "Early_MV2_TV",
    ]
    rng = np.random.default_rng(base.MASTER_SEED + 941)
    rows = []
    for case, group in metrics.groupby("case"):
        piv = group.pivot(index="scenario_id", columns="controller", values=metric_columns)
        for metric in metric_columns:
            x = piv[(metric, WITHOUT)].to_numpy(float)
            y = piv[(metric, HOLD)].to_numpy(float)
            valid = np.isfinite(x) & np.isfinite(y)
            x, y = x[valid], y[valid]
            if not len(x):
                continue
            delta = y - x
            boot = np.mean(delta[rng.integers(0, len(delta), size=(10000, len(delta)))], axis=1)
            rows.append({
                "case": case, "metric": metric, "n_paired": len(delta),
                "mean_difference_hold_minus_withoutDV": float(np.mean(delta)),
                "relative_change_percent": float((np.mean(y) - np.mean(x)) / np.mean(x) * 100) if abs(np.mean(x)) > 1e-12 else np.nan,
                "bootstrap_CI_lower": float(np.quantile(boot, .025)), "bootstrap_CI_upper": float(np.quantile(boot, .975)),
                "d_z": float(np.mean(delta) / np.std(delta, ddof=1)) if len(delta) > 1 and np.std(delta, ddof=1) > 1e-12 else np.nan,
            })
    return pd.DataFrame(rows)


def summary_table(metrics: pd.DataFrame) -> pd.DataFrame:
    numeric = [c for c in metrics.columns if c not in ("case", "scenario_id", "controller", "level")]
    rows = []
    for (case, controller), group in metrics.groupby(["case", "controller"]):
        row = {"case": case, "controller": controller, "n": len(group)}
        for col in numeric:
            vals = group[col].to_numpy(float)
            row[f"{col}_mean"] = float(np.nanmean(vals)) if np.isfinite(vals).any() else np.nan
            row[f"{col}_SD"] = float(np.nanstd(vals, ddof=1)) if np.isfinite(vals).sum() > 1 else np.nan
            if "recovery_time" in col:
                row[f"{col}_observed_n"] = int(np.isfinite(vals).sum())
        rows.append(row)
    return pd.DataFrame(rows)


def sanity_checks(timeseries: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for (level, case, controller, sid), g in timeseries.groupby(["level", "case", "controller", "scenario_id"]):
        true_dv = np.column_stack([g[f"{n}_true"].to_numpy() for n in base.DV_NAMES])
        has_cond = bool(np.any(np.abs(true_dv[:, 3]) > 0))
        has_makeup = bool(np.any(np.abs(true_dv[:, 4]) > 0))
        other_zero = bool(np.allclose(true_dv[:, :3], 0) and (case != "A_condensate_flow_only" or np.allclose(true_dv[:, 4], 0)) and (case != "B_makeup_flow_only" or np.allclose(true_dv[:, 3], 0)))
        has_unmeasured = bool(np.any(np.abs(g[[f"{n}_unmeasured_dist" for n in base.CV_NAMES]].to_numpy()) > 0))
        control_dv = np.column_stack([g[f"{n}_controller_input"].to_numpy() for n in base.DV_NAMES])
        rows.append({"level": level, "case": case, "controller": controller, "scenario_id": sid,
                     "condensate_event_present": has_cond, "makeup_event_present": has_makeup,
                     "other_measured_DV_true_zero": other_zero,
                     "unmeasured_disturbance_present": has_unmeasured,
                     "without_DV_controller_input_zero": bool(np.allclose(control_dv, 0)) if controller == WITHOUT else True,
                     "hold_controller_uses_measured_DV": bool(np.allclose(control_dv, np.column_stack([g[f"{n}_measured"].to_numpy() for n in base.DV_NAMES]))) if controller == HOLD else True})
    checks = pd.DataFrame(rows)
    # Deterministic event assertions only; stochastic background is allowed in level 2.
    clean = checks[checks.level == "clean"]
    if not clean[(clean.case == "A_condensate_flow_only")].condensate_event_present.all(): raise RuntimeError("Case A check failed")
    if not clean[(clean.case == "B_makeup_flow_only")].makeup_event_present.all(): raise RuntimeError("Case B check failed")
    if clean[(clean.case == "C_unmeasured_only")][["condensate_event_present", "makeup_event_present"]].any().any(): raise RuntimeError("Case C check failed")
    if not checks.without_DV_controller_input_zero.all() or not checks.hold_controller_uses_measured_DV.all(): raise RuntimeError("Controller DV-path check failed")
    return checks


def pairing_audit(timeseries: pd.DataFrame) -> pd.DataFrame:
    """Verify controller-exogenous paths are exactly paired by case/scenario."""
    rows = []
    for (level, case, sid), group in timeseries.groupby(["level", "case", "scenario_id"]):
        a = group[group.controller == WITHOUT].sort_values("time_min")
        b = group[group.controller == HOLD].sort_values("time_min")
        if len(a) != T or len(b) != T:
            raise RuntimeError(f"Incomplete paired trajectory: {level}, {case}, {sid}")
        diffs = []
        for name in base.DV_NAMES:
            diffs.extend([
                np.max(np.abs(a[f"{name}_true"].to_numpy() - b[f"{name}_true"].to_numpy())),
                np.max(np.abs(a[f"{name}_measured"].to_numpy() - b[f"{name}_measured"].to_numpy())),
            ])
        for name in base.CV_NAMES:
            diffs.extend([
                np.max(np.abs(a[f"{name}_unmeasured_dist"].to_numpy() - b[f"{name}_unmeasured_dist"].to_numpy())),
                # Measured-minus-true is the stored CV measurement-noise path.
                np.max(np.abs((a[f"{name}_measured"] - a[f"{name}_true"]).to_numpy() - (b[f"{name}_measured"] - b[f"{name}_true"]).to_numpy())),
            ])
        max_difference = float(max(diffs))
        rows.append({"level": level, "case": case, "scenario_id": sid,
                     "same_seed": bool(a.random_seed.iloc[0] == b.random_seed.iloc[0]),
                     "max_abs_exogenous_trace_difference": max_difference,
                     "audit_pass": bool(max_difference < 1e-14 and a.random_seed.iloc[0] == b.random_seed.iloc[0])})
    audit = pd.DataFrame(rows)
    if not audit.audit_pass.all():
        raise RuntimeError("Controller pairs do not share identical exogenous paths")
    return audit


