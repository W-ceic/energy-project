def main() -> None:
    global pair_denominators
    manifest = json.loads((SOURCE_OUT / "simulation_manifest.json").read_text(encoding="utf-8"))
    if manifest["P"] != 40 or manifest["M"] != 5:
        raise RuntimeError("Existing baseline manifest does not contain the fixed P=40, M=5 controller")
    base.configure_horizon(40)
    pidpars = manifest["PID_parameters"]
    _source, templates, source_stage = _source_events()
    template_rows = []
    for key in ("condensate", "makeup"):
        arr = _shifted_dv_template(templates[key])
        for k in range(T):
            template_rows.append({"case": key, "time_min": k, "source_scenario_id": 7, "source_start_min": templates[key]["start_min"], "analysis_start_min": T0, "waveform_value": arr[k, templates[key]["dv_index"]]})
    for k in range(T):
        template_rows.append({"case": "unmeasured", "time_min": k, "source_scenario_id": 7, "source_start_min": templates["unmeasured"]["start_min"], "analysis_start_min": T0, "waveform_value": float(np.linalg.norm(source_stage)) if T0 <= k < T0 + templates["unmeasured"]["duration_min"] else 0.0})
    pd.DataFrame(template_rows).to_csv(OUT / "isolated_disturbance_event_templates.csv", index=False)

    frames, metric_rows = [], []
    for case in CASES:
        for level, ids in (("clean", (0,)), ("stochastic", TEST_IDS)):
            for sid in ids:
                scn = make_isolated_scenario(case, sid, level, templates, source_stage)
                for controller in (WITHOUT, HOLD):
                    frame = run_controller(scn, controller, pidpars, case, level)
                    frames.append(frame)
                    metric_rows.append(event_metrics(frame))
    timeseries = pd.concat(frames, ignore_index=True)
    metrics = pd.DataFrame(metric_rows)
    checks = sanity_checks(timeseries)
    audit = pairing_audit(timeseries)
    stochastic = metrics[metrics.level == "stochastic"].copy()
    clean_metrics = metrics[metrics.level == "clean"].copy()
    stats = paired_statistics(stochastic)
    summary = summary_table(stochastic)
    pair_denominators = {(case, metric): float(group[group.controller == WITHOUT][metric].mean()) for case, group in stochastic.groupby("case") for metric in ["Total_event_pH_IAE", "HP_peak_deviation", "IP_peak_deviation", "Total_MV_TV_event"]}

    timeseries.to_csv(OUT / "isolated_disturbance_timeseries.csv", index=False)
    clean_metrics.to_csv(OUT / "isolated_disturbance_clean_metrics.csv", index=False)
    stochastic.to_csv(OUT / "isolated_disturbance_scenario_level.csv", index=False)
    summary.to_csv(OUT / "isolated_disturbance_summary.csv", index=False)
    stats.to_csv(OUT / "isolated_disturbance_pairwise_statistics.csv", index=False)
    checks.to_csv(OUT / "isolated_disturbance_sanity_checks.csv", index=False)
    audit.to_csv(OUT / "isolated_disturbance_pairing_audit.csv", index=False)
    plot_response(timeseries[timeseries.level == "clean"])
    plot_statistics(stats)
    write_report(templates, source_stage, stochastic, stats, checks)
    manifest_out = {
        "analysis": "isolated single disturbance-event DV information experiment",
        "source_template": "scenario_id=7 regenerated from saved seed and existing event generator",
        "t0_min": T0, "duration_min": T, "event_window_min": [WINDOW_START, WINDOW_END], "early_window_min": [T0, EARLY_END],
        "levels": {"clean": "nominal, no measurement noise, no AR(1) background", "stochastic": "30 matched scenario_id=1..30 with existing mismatch, noises, and AR(1) background"},
        "controllers": {WITHOUT: "d_ctrl=d_hat=0 and nominal model advances with zero DV", HOLD: "d_ctrl=d_meas and P-step zero-order hold"},
        "bootstrap": "10000 paired percentile resamples; hold minus without-DV", "no_retuning": True,
    }
    (OUT / "isolated_disturbance_manifest.json").write_text(json.dumps(manifest_out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"output_dir": str(OUT), "stochastic_rows": len(stochastic), "statistics_rows": len(stats), "sanity_checks": len(checks)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
