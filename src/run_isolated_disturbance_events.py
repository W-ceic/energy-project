def plot_statistics(stats: pd.DataFrame, filename_stem: str = "isolated_DV_event_statistics") -> None:
    selected = ["Total_event_pH_IAE", "HP_peak_deviation", "IP_peak_deviation", "Total_MV_TV_event"]
    labels = {"Total_event_pH_IAE": "Total pH event IAE", "HP_peak_deviation": "HP peak deviation", "IP_peak_deviation": "IP peak deviation", "Total_MV_TV_event": "Total MV TV"}
    order = list(CASES)
    fig, axes = plt.subplots(2, 2, figsize=(7.5, 5.4), sharey=True)
    axes = axes.ravel()
    markers = ["o", "s", "D"]
    panel_prefixes = ["(a)", "(b)", "(c)", "(d)"]
    for panel_prefix, ax, metric in zip(panel_prefixes, axes, selected):
        sub = stats[stats.metric == metric].set_index("case").reindex(order)
        y = np.arange(len(order))
        values = sub.relative_change_percent.to_numpy(float)
        lo = sub.bootstrap_CI_lower.to_numpy(float)
        hi = sub.bootstrap_CI_upper.to_numpy(float)
        # Convert CI of absolute paired difference to relative units using the
        # corresponding without-DV mean recovered from the scenario data.
        # The plot's points retain exact CSV values; intervals are computed below.
        relative_ci = []
        for i, case in enumerate(order):
            denom = pair_denominators[(case, metric)]
            relative_ci.extend([100 * lo[i] / denom, 100 * hi[i] / denom, values[i]])
        limit = max(0.5, max(abs(x) for x in relative_ci) * 1.16)
        # The first three error metrics have comparable percent units, so a
        # common range enables direct visual comparison without clipping CIs.
        ax.set_xlim((-8, 6) if metric != "Total_MV_TV_event" else (-limit, limit))
        ax.spines["left"].set_visible(False)
        ax.tick_params(axis="y", length=0)
        ax.axvline(0, color="#777777", lw=.8, zorder=0)
        for i, case in enumerate(order):
            denom = pair_denominators[(case, metric)]
            xlo, xhi = 100 * lo[i] / denom, 100 * hi[i] / denom
            ax.errorbar(values[i], i, xerr=[[values[i] - xlo], [xhi - values[i]]], fmt=markers[i],
                        color="#333333", capsize=2, ms=4.5)
        ax.set_title(f"{panel_prefix} {labels[metric]}", fontsize=8)
        ax.set_xlabel("")
        ax.set_yticks(y)
        ax.set_yticklabels([CASES[x]["label"].replace("-only", "") for x in order])
        ax.invert_yaxis()
    fig.supxlabel("Relative change of DMC-DV hold versus DMC-without-DV (%)", fontsize=8, y=.02)
    fig.tight_layout(rect=(0, .055, 1, 1))
    fig.savefig(OUT / f"{filename_stem}.png", dpi=350)
    fig.savefig(OUT / f"{filename_stem}.pdf")
    plt.close(fig)


